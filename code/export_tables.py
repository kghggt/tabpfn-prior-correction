def _fmt_p(p: float) -> str:
    if p != p:
        return "--"
    if p < 1e-3:
        return f"$<10^{{-3}}$"
    return f"${p:.3f}$"


GRID_LABEL = {
    "main12": "twelve-table grid",
    "rare12": "naturally rare panel",
    "extended": "extended grid",
    "shift": "subpopulation-shift protocol",
    "heldout": "held-out tables",
}


def write_mean_table(summary, path, caption_note="", grid="main12"):
    methods = summary["methods"]
    cols = [c for c in MAIN_COLUMNS if c in methods]
    lines = []
    lines.append("\\begin{table}[t]")
    lines.append("\\centering")
    lines.append("\\small")
    setting_lbl = SETTING_LABEL.get(summary["setting"], summary["setting"])
    version_lbl = VERSION_LABEL.get(summary["model_version"], summary["model_version"])
    cap = (
        "Mean macro-F1 on the "
        + GRID_LABEL.get(grid, grid)
        + ", {} split, TabPFN {} weights ($n={}$ tables, seeds averaged). "
        "+OS copies minority rows; +SMOTE interpolates; BalCtx downsamples the majority class; "
        "Thr searches a hold-out threshold; PICL, DistPFN and DistPFN-T are closed-form prior "
        "corrections with, respectively, a uniform target, the model's own mean predicted test "
        "distribution, and its temperature-scaled form; Oracle uses the test prevalence and is "
        "not deployable. Generated by \\texttt{{code/export\\_tables.py}} from "
        "\\texttt{{results/}}.{}"
    ).format(setting_lbl, version_lbl, summary["n_datasets"], caption_note)
    lines.append("\\caption{" + cap + "}")
    lines.append("\\label{tab:mean_gen_" + re.sub(r"[^a-zA-Z0-9]", "", f"{grid}{summary['setting']}{version_lbl}") + "}")
    lines.append("\\setlength{\\tabcolsep}{3pt}")
    lines.append("{\\scriptsize")
    lines.append("\\begin{tabular}{l" + "c" * len(cols) + "}")
    lines.append("\\toprule")
    lines.append(" & ".join(["Method"] + [LABEL.get(c, c) for c in cols]) + " \\\\")
    lines.append("\\midrule")
    row = []
    for c in cols:
        row.append(f"{methods[c]['mean']:.3f}")
    lines.append(" & ".join(["mean"] + row) + " \\\\")
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append("}")
    lines.append("\\end{table}")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    return path


def write_test_table(summary, path):
    tests = summary["tests"]
    if not tests:
        return None
    lines = []
    lines.append("\\begin{table}[t]")
    lines.append("\\centering")
    lines.append("\\small")
    lines.append(
        f"\\caption{{One-sided Wilcoxon signed-rank tests on per-dataset macro-F1 means, "
        f"{SETTING_LABEL.get(summary['setting'], summary['setting'])} split, "
        f"TabPFN {VERSION_LABEL.get(summary['model_version'], summary['model_version'])} "
        f"($n={summary['n_datasets']}$). Alternative is ``greater'' for the first method named.}}"
    )
    lines.append(
        "\\label{tab:tests_gen_"
        + re.sub(r"[^a-zA-Z0-9]", "", summary["setting"] + summary["model_version"])
        + "}"
    )
    lines.append("\\begin{tabular}{llccccc}")
    lines.append("\\toprule")
    lines.append("A & B & mean(A) & mean(B) & $\\Delta$ & wins & $p$ \\\\")
    lines.append("\\midrule")
    for key, t in tests.items():
        a, b = key.split("_vs_")
        lines.append(
            f"{LABEL.get(a, a)} & {LABEL.get(b, b)} & {t['mean_a']:.3f} & {t['mean_b']:.3f} & "
            f"{t['mean_diff']:+.3f} & {t['wins_a']}/{t['n']} & {_fmt_p(t['p_one_sided'])} \\\\"
        )
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append("\\end{table}")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    return path


